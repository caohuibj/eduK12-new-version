def parameter_band_label(key, empirical):
    return (EMPIRICAL_LABELS if empirical else THEORETICAL_LABELS)[key]


def anchor_guide(score):
    if score == 'academic_self_concept':
        return '若页面显示均分，可对照原作答选项：1＝完全不同意，2＝不同意，3＝中性，4＝同意，5＝完全同意。均分为3不表示每题都选中性。'
    if score == 'academic_self_efficacy':
        return '若页面显示均分，可对照原作答选项：1＝完全不同意，2＝不同意，3＝一般，4＝同意，5＝完全同意。“一般”不是客观中等能力。'
    second, fifth = ('比较不同意', '比较同意') if score == 'teacher_subject_liking' else ('不同意', '同意')
    return f'若页面显示均分，可对照原作答选项：1＝完全不同意，2＝{second}，3＝有点不同意，4＝有点同意，5＝{fifth}，6＝完全同意。3.5没有对应的中性选项；相同均分可来自不同回答。'


def report_limitations(family, empirical):
    values = [
        '这份结果描述本次自评，不是智力、实际成绩、天赋或心理疾病的测量，也不预测未来一定怎样。',
        '相同均分可能来自不同题目组合；单次均分不能证明情绪、行为频率、变化趋势或形成原因。',
        '缺失作答不会记为低分；达到原计分要求的结果仍应结合完整性提示理解，不足时不作解释。',
        '分段是描述，不是个人标签；不同学科、学段或参考组的分段不能直接比较。',
    ]
    values.append('历史便利样本的相对位置不等于作答认同程度，不代表总体常模或能力排名。' if empirical else '理论范围分段是暂定描述初版，不是人群常模、经验证的心理阈值或诊断界线；不提供样本排名或百分位。')
    if family == 'value_cost':
        values.append('价值和时间代价分别报告，不相加、不相减，也不合成一个好坏总分。')
    if family == 'tutoring_necessity':
        values.append('这里只测对补习帮助与必要性的信念，不证明补习有效或客观需要，也不是购买建议。')
    if family == 'teacher_subject_liking':
        values.append('这里是学生感知，不是教师自评、老师真实内心或教学质量，不能用于教师排名与问责。')
    if family == 'domain_fixed_mindset':
        values.append('较少认同固定信念，不等于已经测得高成长心态，也不证明某种学习策略或行为。')
    return values


def report_for(score, subject, empirical=False):
    content = REPORTS[score]
    fmt = lambda text: text.replace('{学科}', subject)
    context = fmt(content.get('context', SUBJECT_CONTEXT[subject]))
    context += '这里只是可选择的反思例子。'
    meaning = fmt(content['meaning'])
    boundary = fmt(content['boundary'])
    anchors = anchor_guide(score)
    variants = []
    for index, key in enumerate(KEYS):
        label = parameter_band_label(key, empirical)
        if empirical:
            placement = f'本次得分在同学科、同学段历史参考组中相对{POSITIONS[index]}，不等于对题目的绝对认同程度。即使相对偏低，均分仍可能偏向同意；相对偏高也未必偏向同意。便利样本不代表所有同学。'
        else:
            placement = f'本次得分在量尺的暂定{POSITIONS[index]}分段。这按可选分数范围划分，不是同学中的位置，也不是经数据验证的心理转折点；中间分段不表示犹豫或想法来回变化。'
        reflection, action = content['guidance'][index]
        variants.append({
            'key': key,
            'label': fmt(content['headline']) + '：' + label,
            'summary': '\n\n'.join([meaning, placement, anchors, boundary]),
            'guidance': [{'category': 'reflection', 'text': fmt(reflection)}, {'category': 'strategy', 'text': fmt(action)}],
        })
    fallback = '当前没有匹配的同学科、同学段参考时，不提供分段或百分位。未显示数值时，不必猜测均分；可以回想题目含义与自己的选择。下面只是可选择的反思方式。'
    return {
        'scoreKey': score,
        'headline': fmt(content['headline']),
        'source': {'type': 'reference_context'},
        'summary': '\n\n'.join([meaning, anchors, fallback, boundary, context]),
        'bands': variants,
        'guidance': [
            {'category': 'reflection', 'text': fmt(content['guidance'][2][0])},
            {'category': 'strategy', 'text': fmt(content['guidance'][2][1])},
        ],
    }

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const backendRoot = path.resolve(scriptDir, '..')
const serverRoot = path.resolve(backendRoot, '..')
const backendTasksRoot = path.join(backendRoot, 'src/modules/cognitive/tasks')
const frontendTasksRoot = path.join(serverRoot, 'frontend/src/modules/cognitive/tasks')
const checkOnly = new Set(process.argv.slice(2)).has('--check')

const taskDirectories = (root) => fs.readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .filter((name) => !name.startsWith('.') && name !== 'generated')
  .sort()

const backendTasks = taskDirectories(backendTasksRoot)
  .filter((task) => fs.existsSync(path.join(backendTasksRoot, task, 'package.ts')))
const frontendTasks = taskDirectories(frontendTasksRoot)
  .filter((task) => fs.existsSync(path.join(frontendTasksRoot, task, `${task}.registry.ts`)))

const mismatch = [
  ...backendTasks.filter((task) => !frontendTasks.includes(task)),
  ...frontendTasks.filter((task) => !backendTasks.includes(task)),
]
if (mismatch.length > 0) {
  throw new Error(`Cognitive backend/frontend task discovery mismatch: ${[...new Set(mismatch)].sort().join(', ')}`)
}

const readExport = (filePath, pattern, label) => {
  const source = fs.readFileSync(filePath, 'utf8')
  const match = source.match(pattern)
  if (!match) throw new Error(`Missing ${label} export in ${filePath}`)
  return match[1]
}

const backendRows = backendTasks.map((task) => ({
  task,
  exportName: readExport(
    path.join(backendTasksRoot, task, 'package.ts'),
    /export const ([A-Za-z0-9_]+TaskPackage)\s*=/,
    'TaskPackage',
  ),
}))
const frontendRows = frontendTasks.map((task) => ({
  task,
  exportName: readExport(
    path.join(frontendTasksRoot, task, `${task}.registry.ts`),
    /export const ([A-Za-z0-9_]+RegistryEntry)\s*[:=]/,
    'RegistryEntry',
  ),
}))

const header = '// AUTO-GENERATED by scripts/generate-cognitive-manifests.mjs. DO NOT EDIT.\n'
const backendContent = header
  + backendRows.map(({ task, exportName }) => `import { ${exportName} } from '../${task}/package'`).join('\n')
  + '\n\nexport const COGNITIVE_TASK_PACKAGES = [\n'
  + backendRows.map(({ exportName }) => `  ${exportName},`).join('\n')
  + '\n] as const\n\nexport const COGNITIVE_TASK_TYPES = [\n'
  + backendRows.map(({ task }) => `  '${task}',`).join('\n')
  + '\n] as const\n'

const frontendContent = '// AUTO-GENERATED by backend/scripts/generate-cognitive-manifests.mjs. DO NOT EDIT.\n'
  + frontendRows.map(({ task, exportName }) => `import { ${exportName} } from '../tasks/${task}/${task}.registry'`).join('\n')
  + '\n\nexport const COGNITIVE_RUNNER_ENTRIES = [\n'
  + frontendRows.map(({ exportName }) => `  ${exportName},`).join('\n')
  + '\n] as const\n\nexport const COGNITIVE_FRONTEND_TASK_TYPES = [\n'
  + frontendRows.map(({ task }) => `  '${task}',`).join('\n')
  + '\n] as const\n'

const seedContent = header
  + 'export const COGNITIVE_SEED_TASK_TYPES = [\n'
  + backendRows.map(({ task }) => `  '${task}',`).join('\n')
  + '\n] as const\n'

const outputs = [
  [path.join(backendTasksRoot, 'generated/task-packages.generated.ts'), backendContent],
  [path.join(serverRoot, 'frontend/src/modules/cognitive/generated/runners.generated.ts'), frontendContent],
  [path.join(backendRoot, 'prisma/seeds/cognitive-task-types.generated.ts'), seedContent],
]

const drift = []
for (const [filePath, content] of outputs) {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null
  if (existing === content) continue
  if (checkOnly) {
    drift.push(path.relative(serverRoot, filePath))
    continue
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, content)
}

if (drift.length > 0) {
  console.error('Cognitive generated manifest drift:')
  for (const filePath of drift) console.error(` - ${filePath}`)
  console.error('Run: npm run cognitive:manifest:generate')
  process.exit(1)
}

if (!checkOnly) console.log(`Generated Cognitive manifests for ${backendRows.length} task packages.`)

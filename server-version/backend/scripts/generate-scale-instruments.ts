import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, relative } from 'node:path'
const target = resolve(process.cwd(), 'src/modules/scale/onboarding/instruments.generated.ts')
const sourceRoot = resolve(process.cwd(), 'src/modules/scale/instruments')
const discoverFiles = (dir: string, filename: string): string[] => !existsSync(dir) ? [] : readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
  const path = resolve(dir, entry.name)
  return entry.isDirectory() ? discoverFiles(path, filename) : entry.isFile() && entry.name === filename ? [path] : []
}).sort()
const portableRelative = (from: string, to: string) => relative(from, to).replace(/\\/g, '/')
const sourceFiles = discoverFiles(sourceRoot, 'instrument.ts')
if (sourceFiles.length === 0) throw new Error('No Scale instrument sources found')
const sourceImports = sourceFiles.map((path, index) => `import { SCALE_INSTRUMENT_SOURCE as source${index} } from '${relative(resolve(target, '..'), path).replace(/\\/g, '/').replace(/\.ts$/, '')}'`).join('\n')
const sourceEntries = sourceFiles.map((_, index) => `  source${index},`).join('\n')
const expected = `// AUTO-GENERATED by scripts/generate-scale-instruments.ts. DO NOT EDIT.
// Production runtime imports this static file and never scans the filesystem.
${sourceImports}
import type { ScaleInstrumentSourceV1, ScalePackageV2, VersionedScorerRegistration } from './types'

/** Legacy descriptor arrays are intentionally empty after PR-4 source migration. */
export const GENERATED_EXECUTABLE_SCALE_PACKAGES: readonly ScalePackageV2[] = []
export const GENERATED_SCALE_SCORER_PLUGINS: readonly VersionedScorerRegistration[] = []

export const GENERATED_SCALE_INSTRUMENT_SOURCES: readonly ScaleInstrumentSourceV1[] = [
${sourceEntries}
]
`
const legacyTarget = resolve(target, '../report-variants.generated.ts')
const legacyFiles = discoverFiles(sourceRoot, 'report-variants.json')
const legacyImports = legacyFiles.map((path, index) => `import material${index} from '${portableRelative(resolve(legacyTarget, '..'), path)}'`)
const legacyEntries = legacyFiles.map((path, index) =>
  `  {material: material${index}, origin: legacyOrigin(${JSON.stringify(portableRelative(sourceRoot, path))})},`)
const legacyExpected = [
  '// AUTO-GENERATED by scripts/generate-scale-instruments.ts. DO NOT EDIT.',
  '// Historical references stay stable. Current declarations are discovered by the deployment command.',
  'import origins from \'./report-variants.legacy-origins.json\'',
  ...legacyImports,
  '',
  'const historicalOrigins: Record<string, {commit?:string;path:string}> = origins',
  'const legacyOrigin = (path:string) => historicalOrigins[path] ?? {path: \'server-version/backend/src/modules/scale/instruments/\' + path}',
  '',
  'export const GENERATED_LEGACY_SCALE_REPORT_MATERIALS = [',
  ...legacyEntries,
  '] as const',
  '',
].join('\n')

for (const [file, content] of [[target, expected], [legacyTarget, legacyExpected]] as const) {
  if (!process.argv.includes('--check')) {
    writeFileSync(file, content, 'utf8')
  } else if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
    console.error(`Generated Scale index is stale (${file}). Run: npm run scale:instruments:generate`)
    process.exitCode = 1
  }
}

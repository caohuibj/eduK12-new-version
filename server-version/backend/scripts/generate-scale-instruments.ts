import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, relative } from 'node:path'
const target = resolve(process.cwd(), 'src/modules/scale/onboarding/instruments.generated.ts')
const sourceRoot = resolve(process.cwd(), 'src/modules/scale/instruments')
const discoverSources = (dir: string): string[] => !existsSync(dir) ? [] : readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
  const path = resolve(dir, entry.name)
  return entry.isDirectory() ? discoverSources(path) : entry.name === 'instrument.ts' ? [path] : []
}).sort()
const sourceFiles = discoverSources(sourceRoot)
if (sourceFiles.length === 0) throw new Error('No Scale instrument sources found')
const sourceImports = sourceFiles.map((path, index) => `import { SCALE_INSTRUMENT_SOURCE as source${index} } from '${relative(resolve(target, '..'), path).replace(/\\/g, '/').replace(/\.ts$/, '')}'`).join('\n')
const sourceEntries = sourceFiles.map((_, index) => `  source${index},`).join('\n')
const expected = `// AUTO-GENERATED by scripts/generate-scale-instruments.ts. DO NOT EDIT.
// Production runtime imports this static file and never scans the filesystem.
${sourceImports}
import type { ScaleInstrumentSourceV1, ScalePackageV2, VersionedScorerRegistration } from './types'

/** Legacy descriptor arrays are intentionally empty after PR-4 source migration. */
export const GENERATED_EXECUTABLE_SCALE_PACKAGES: readonly ScalePackageV2[] = []
export const GENERATED_SCALE_SCORER_PLUGINS: readonly VersionedScorerRegistration[] = []

export const GENERATED_SCALE_INSTRUMENT_SOURCES: readonly ScaleInstrumentSourceV1[] = [
${sourceEntries}
]
`
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8')
  if (current !== expected) { console.error('Scale instrument generated index is stale. Run: npm run scale:instruments:generate'); process.exit(1) }
  process.exit(0)
}
writeFileSync(target, expected, 'utf8')

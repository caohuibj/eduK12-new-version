import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, relative } from 'node:path'
const target = resolve(process.cwd(), 'src/modules/scale/onboarding/instruments.generated.ts')
const reportVariantTarget = resolve(process.cwd(), 'src/modules/scale/onboarding/report-variants.generated.ts')
const sourceRoot = resolve(process.cwd(), 'src/modules/scale/instruments')
const discoverFiles = (dir: string, fileName: string): string[] => !existsSync(dir) ? [] : readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
  const path = resolve(dir, entry.name)
  return entry.isDirectory() ? discoverFiles(path, fileName) : entry.name === fileName ? [path] : []
}).sort()
const sourceFiles = discoverFiles(sourceRoot, 'instrument.ts')
if (sourceFiles.length === 0) throw new Error('No Scale instrument sources found')
const sourceImports = sourceFiles.map((path, index) => `import { SCALE_INSTRUMENT_SOURCE as source${index} } from '${relative(resolve(target, '..'), path).replace(/\\/g, '/').replace(/\.ts$/, '')}'`).join('\n')
const sourceEntries = sourceFiles.map((_, index) => `  source${index},`).join('\n')
const expected = `// AUTO-GENERATED by scripts/generate-scale-instruments.ts. DO NOT EDIT.
// Production runtime imports this static file and never scans the filesystem.
${sourceImports}
import type { ScaleInstrumentSourceV1, ScalePackageV2, VersionedScorerRegistration } from './types'

/** Legacy descriptor arrays are intentionally empty after PR-4 source migration. */
export const GENERATED_EXECUTABLE_SCALE_PACKAGES: readonly ScalePackageV2[] = []
export const GENERATED_SCALE_SCORER_PLUGINS: readonly VersionedScorerRegistration[] = []

export const GENERATED_SCALE_INSTRUMENT_SOURCES: readonly ScaleInstrumentSourceV1[] = [
${sourceEntries}
]
`
const reportVariantFiles = discoverFiles(sourceRoot, 'report-variants.json')
const reportVariantImports = reportVariantFiles.map((path, index) => `import material${index} from '${relative(resolve(reportVariantTarget, '..'), path).replace(/\\/g, '/')}'`).join('\n')
const reportVariantEntries = reportVariantFiles.map((path, index) => {
  const repositoryPath = relative(resolve(process.cwd(), '../..'), path).replace(/\\/g, '/')
  return `  { material: material${index}, path: '${repositoryPath}' },`
}).join('\n')
const expectedReportVariants = `// AUTO-GENERATED by scripts/generate-scale-instruments.ts. DO NOT EDIT.
// Runtime imports this static inventory and never scans the filesystem.
${reportVariantImports}

export const GENERATED_SCALE_REPORT_VARIANT_MATERIALS: readonly { material: unknown; path: string }[] = [
${reportVariantEntries}
]
`
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8')
  if (current !== expected) { console.error('Scale instrument generated index is stale. Run: npm run scale:instruments:generate'); process.exit(1) }
  const currentReportVariants = readFileSync(reportVariantTarget, 'utf8')
  if (currentReportVariants !== expectedReportVariants) { console.error('Scale report variant generated index is stale. Run: npm run scale:instruments:generate'); process.exit(1) }
  process.exit(0)
}
writeFileSync(target, expected, 'utf8')
writeFileSync(reportVariantTarget, expectedReportVariants, 'utf8')

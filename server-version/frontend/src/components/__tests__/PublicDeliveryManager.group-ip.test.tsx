import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { PublicDeliveryManager } from '../PublicDeliveryManager'
const api=vi.hoisted(()=>({get:vi.fn(),post:vi.fn(),delete:vi.fn()}))
vi.mock('../../api/client',()=>({default:api,sessionFetch:vi.fn()}))
vi.mock('../AnonymousStudyManager',()=>({AnonymousStudyManager:()=>null}))
afterEach(()=>vi.restoreAllMocks())
const now=Date.parse('2026-10-19T00:00:00Z')
const row={id:'link',token:'real-token',createdAt:null,expiresAt:'2026-10-19T01:00:00Z',maxUses:0,usedCount:0,isActive:true,roundId:'frozen-round',groupIpWindow:{opensAt:'2026-10-19T00:00:00Z',closesAt:'2026-10-19T01:00:00Z'}}
beforeEach(()=>{vi.clearAllMocks();vi.spyOn(Date,'now').mockReturnValue(now);api.get.mockResolvedValue({code:0,data:{list:[]}});api.post.mockResolvedValue({code:0,data:row})})
async function ready(){await screen.findByText('尚未生成链接')}
function expiry(){fireEvent.change(screen.getByLabelText('有效期'),{target:{value:'2026-10-19T01:00'}})}
it('defaults off and sends policy only after explicit opt-in',async()=>{
 render(<PublicDeliveryManager family="COMPOSITE" resourceId="task" groupIpEligible />)
 await ready();expiry()
 const checkbox=screen.getByRole('checkbox',{name:'为此新链接启用同 IP 集体作答短窗口'})
 expect(checkbox).not.toBeChecked()
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 await waitFor(()=>expect(api.post).toHaveBeenCalledTimes(1))
 expect(api.post.mock.calls[0][1]).not.toHaveProperty('groupIpPolicy')
 await screen.findByText('匿名链接已生成')
 fireEvent.click(checkbox)
 fireEvent.change(screen.getByLabelText('窗口时区（IANA）'),{target:{value:'Asia/Shanghai'}})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 await waitFor(()=>expect(api.post).toHaveBeenCalledTimes(2))
 expect(api.post.mock.calls[1][1]).toMatchObject({groupIpPolicy:{schemaVersion:1,timeZone:'Asia/Shanghai'}})
 expect(screen.getByText(/已有恢复凭证仍按原作答规则恢复/)).toBeInTheDocument()
 expect(screen.getByText(/同 IP 短窗口：/)).toHaveTextContent('frozen-round')
})
it('does not expose opt-in without verified Training eligibility or for other families',async()=>{
 const view=render(<PublicDeliveryManager family="COMPOSITE" resourceId="task" />)
 await ready();expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
 view.rerender(<PublicDeliveryManager family="QUESTIONNAIRE" resourceId="other" groupIpEligible />)
 await ready();expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
})
it('rejects overlong windows and task cutoff before creating any link',async()=>{
 render(<PublicDeliveryManager family="COMPOSITE" resourceId="task" groupIpEligible maximumExpiry="2026-10-22T00:00:00Z" />)
 await ready();fireEvent.click(screen.getByRole('checkbox'))
 fireEvent.change(screen.getByLabelText('有效期'),{target:{value:'2026-10-21T01:00'}})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('最长为 48 小时')
 fireEvent.change(screen.getByLabelText('有效期'),{target:{value:'2026-10-23T01:00'}})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('不能晚于测评截止时间')
 expect(api.post).not.toHaveBeenCalled()
})
it('reveals and copies the exact bound credential, never a round-only link',async()=>{
 api.get.mockResolvedValue({code:0,data:{list:[{...row,token:null}]}})
 const writeText=vi.fn().mockResolvedValue(undefined)
 Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText}})
 render(<PublicDeliveryManager family="COMPOSITE" resourceId="task" groupIpEligible />)
 await screen.findByText(/同 IP 短窗口：/)
 fireEvent.click(screen.getByRole('button',{name:'复制链接'}))
 await waitFor(()=>expect(writeText).toHaveBeenCalledWith(window.location.origin+'/public/composite/real-token'))
 expect(api.post).toHaveBeenCalledWith('/composite-assessments/task/public-tokens/link/reveal',{})
})
it('preserves a loaded link through invalid windows, timezone and rejected server creation',async()=>{
 api.get.mockResolvedValue({code:0,data:{list:[row]}})
 render(<PublicDeliveryManager family="COMPOSITE" resourceId="task" groupIpEligible />)
 await screen.findByText(/同 IP 短窗口：/)
 fireEvent.click(screen.getByRole('checkbox'))
 fireEvent.change(screen.getByLabelText('有效期'),{target:{value:'2026-10-21T01:00'}})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('最长为 48 小时')
 expect(screen.getByRole('link')).toHaveAttribute('href',window.location.origin+'/public/composite/real-token')
 expiry()
 fireEvent.change(screen.getByLabelText('窗口时区（IANA）'),{target:{value:'Invalid/Zone'}})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('有效的 IANA 时区')
 expect(screen.getByRole('link')).toHaveAttribute('href',window.location.origin+'/public/composite/real-token')
 expect(api.get).toHaveBeenCalledTimes(1)
 expect(api.post).not.toHaveBeenCalled()
 fireEvent.change(screen.getByLabelText('窗口时区（IANA）'),{target:{value:'UTC'}})
 api.post.mockRejectedValueOnce({status:409,message:'创建冲突'})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('创建冲突')
 expect(api.get).toHaveBeenCalledTimes(2)
 expect(screen.getByRole('link')).toHaveAttribute('href',window.location.origin+'/public/composite/real-token')
})
it.each([401,403])('clears loaded credentials on create HTTP %s',async status=>{
 api.get.mockResolvedValue({code:0,data:{list:[row]}})
 render(<PublicDeliveryManager family="COMPOSITE" resourceId="task" groupIpEligible />)
 await screen.findByText(/同 IP 短窗口：/);expiry()
 api.post.mockRejectedValueOnce({status,message:'访问权限已失效'})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('访问权限已失效')
 expect(screen.queryByRole('link')).not.toBeInTheDocument()
 expect(api.get).toHaveBeenCalledTimes(1)
})
it('clears loaded credentials when failed creation cannot revalidate list access',async()=>{
 api.get.mockResolvedValueOnce({code:0,data:{list:[row]}})
 render(<PublicDeliveryManager family="COMPOSITE" resourceId="task" groupIpEligible />)
 await screen.findByText(/同 IP 短窗口：/);expiry()
 api.post.mockResolvedValueOnce({code:-1,message:'权限已撤销'})
 api.get.mockRejectedValueOnce({status:403,message:'Forbidden'})
 fireEvent.click(screen.getByRole('button',{name:'生成新链接'}))
 expect(await screen.findByRole('alert')).toHaveTextContent('权限已撤销')
 expect(screen.queryByRole('link')).not.toBeInTheDocument()
})

import {fireEvent,render,screen,waitFor} from '@testing-library/react'
import {expect,it,vi} from 'vitest'
import TrainingAdminResources from './TrainingAdminResources'
import type {Resource} from './trainingResourceCatalog'
const catalog=vi.hoisted(()=>vi.fn())
vi.mock('./trainingResourceCatalog',()=>({trainingResourceCatalog:catalog}))

it('does not rescan catalog rows while editing unapplied filters, but applies queries and fresh rows',async()=>{
 const hiddenCode=vi.fn(()=>'HIDDEN')
 const rows:Resource[]=Array.from({length:25},(_,index)=>({id:String(index),type:'SCALE',name:'Resource '+index,code:'CODE'+index,version:'1',status:'PUBLISHED',grantable:false,note:'Exact version'}))
 Object.defineProperty(rows[24],'code',{get:hiddenCode})
 catalog.mockResolvedValueOnce(rows)
 render(<TrainingAdminResources/>)
 expect(await screen.findByText('Resource 0')).toBeVisible()
 expect(hiddenCode).toHaveBeenCalledTimes(1)
 fireEvent.click(screen.getByRole('button',{name:/资源检索/}))
 const input=screen.getByRole('searchbox',{name:'搜索资源'})
 for(const value of ['R','Re','Res','Resource 24'])fireEvent.change(input,{target:{value}})
 expect(hiddenCode).toHaveBeenCalledTimes(1)
 expect(screen.getByText('Resource 0')).toBeVisible()
 expect(catalog).toHaveBeenCalledTimes(1)
 fireEvent.click(screen.getByRole('button',{name:'查询'}))
 expect(screen.getByText('Resource 24')).toBeVisible()
 expect(screen.queryByText('Resource 0')).not.toBeInTheDocument()
 expect(hiddenCode.mock.calls.length).toBeGreaterThan(1)
 catalog.mockResolvedValueOnce([{...rows[0],id:'fresh',name:'Resource 24 fresh',status:'DRAFT',note:'Publish before grant'}])
 fireEvent.click(screen.getByRole('button',{name:'刷新资源'}))
 expect(await screen.findByText('Resource 24 fresh')).toBeVisible()
 expect(screen.getByText('草稿')).toBeVisible()
 expect(screen.getByRole('button',{name:'管理授权'})).toBeDisabled()
 await waitFor(()=>expect(catalog).toHaveBeenCalledTimes(2))
 fireEvent.click(screen.getByRole('button',{name:/资源检索/}))
 fireEvent.change(screen.getByLabelText('发布状态'),{target:{value:'PUBLISHED'}})
 expect(screen.getByText('Resource 24 fresh')).toBeVisible()
 fireEvent.click(screen.getByRole('button',{name:'查询'}))
 expect(screen.getByText('未找到匹配资源')).toBeVisible()
 fireEvent.click(screen.getByRole('button',{name:'清除筛选'}))
 expect(screen.getByText('Resource 24 fresh')).toBeVisible()
})

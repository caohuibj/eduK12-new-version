import {act,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {describe,it,expect,vi} from 'vitest'
import {SchoolLearnerHome,SchoolLearnerMenu} from './SchoolLearnerHome'
import {SchoolStudentTasks,type SchoolTask} from './SchoolStudentTasks'
import {SchoolWorkspaceShell} from './SchoolWorkspaceShell'
import {schoolNavigation} from './school-navigation'
import type {SchoolApi} from './SchoolRecovery'
const items=schoolNavigation('STUDENT','APPROVED',null,false)
const row=(id:string,activityId:string,title:string,deadline:string|null=null):SchoolTask=>({id,activityId,activityTitle:'校园活动',title,kind:'READING',status:'PENDING',deadline,href:'safe'})
const page=(list:SchoolTask[],total=list.length)=>({list,total,hasMore:total>list.length,page:1,truncated:false})
const first=row('task-a','00000000-0000-4000-8000-000000000001','阅读甲','2026-11-20T00:00:00Z')
const second=row('task-b','00000000-0000-4000-8000-000000000002','阅读乙','2026-11-01T00:00:00Z')
describe('School learner collections',()=>{
 it('keeps equal activity titles separate by identity and preserves exact authorized task destinations',async()=>{
  const api=vi.fn(async()=>page([first,second]))
  render(<SchoolLearnerHome api={api as SchoolApi} username="学生" items={items} onNavigate={vi.fn()}/>)
  const links=await screen.findAllByRole('link',{name:/已开放 校园活动/})
  expect(links).toHaveLength(2)
  expect(links.map(link=>link.getAttribute('href'))).toEqual([`/workspace/tasks?activityId=${first.activityId}`,`/workspace/tasks?activityId=${second.activityId}`])
  expect(screen.queryByText(/欢迎回来/)).not.toBeInTheDocument()
  expect(screen.getByRole('link',{name:/校园任务/})).toHaveTextContent('2项')
  fireEvent.click(screen.getByRole('button',{name:'检索校园活动'}))
  fireEvent.change(screen.getByRole('searchbox',{name:'检索校园活动'}),{target:{value:'阅读乙'}})
  fireEvent.click(screen.getByRole('button',{name:'检索'}))
  expect(screen.getAllByRole('link',{name:/已开放 校园活动/})).toHaveLength(1)
  expect(screen.getByRole('link',{name:/已开放 校园活动/})).toHaveAttribute('href',`/workspace/tasks?activityId=${second.activityId}`)
  expect(api).toHaveBeenCalledTimes(1)
 })
 it('does not fetch tasks without the authorized entry and ignores responses from an old API scope',async()=>{
  const noAccess=vi.fn(),navigate=vi.fn()
  const view=render(<SchoolLearnerHome api={noAccess as SchoolApi} username="待审批" items={schoolNavigation('STUDENT','PENDING_CLASS_APPROVAL',null,false)} onNavigate={navigate}/>)
  expect(noAccess).not.toHaveBeenCalled()
  expect(screen.queryByRole('link',{name:/校园任务/})).not.toBeInTheDocument()
  let finish!:(value:unknown)=>void
  const old=vi.fn(()=>new Promise(resolve=>{finish=resolve})),fresh=vi.fn(async()=>page([{...first,activityTitle:'当前学校活动'}]))
  view.rerender(<SchoolLearnerHome api={old as SchoolApi} username="学生" items={items} onNavigate={navigate}/>)
  view.rerender(<SchoolLearnerHome api={fresh as SchoolApi} username="学生" items={items} onNavigate={navigate}/>)
  await screen.findByRole('heading',{name:'当前学校活动'})
  await act(async()=>finish(page([{...second,activityTitle:'过期学校活动'}])))
  expect(screen.queryByRole('heading',{name:'过期学校活动'})).not.toBeInTheDocument()
 })
 it('labels partial search honestly, applies deadline ordering and keeps source task objects intact',async()=>{
  const data=page([first,second],40),api=vi.fn(async(path:string)=>path==='/my/student-reference'?{reference:'test'}:data)
  const {container}=render(<SchoolStudentTasks api={api as SchoolApi}/>)
  fireEvent.click(await screen.findByRole('button',{name:'检索本页任务'}))
  await screen.findByRole('searchbox',{name:'检索本页任务'})
  expect(screen.getByText(/检索和排序仅作用于本页/)).toBeVisible()
  fireEvent.change(screen.getByRole('combobox',{name:'排序'}),{target:{value:'deadline'}})
  expect(container.querySelector('article')).toHaveAttribute('data-task-id',second.id)
  expect(data.list[0].id).toBe(first.id)
  fireEvent.change(screen.getByRole('searchbox',{name:'检索本页任务'}),{target:{value:'找不到'}})
  fireEvent.click(screen.getByRole('button',{name:'检索'}))
  expect(screen.getByText(/本页没有匹配的任务/)).toBeVisible()
  fireEvent.keyDown(screen.getByRole('searchbox',{name:'检索本页任务'}),{key:'Escape'})
  expect(screen.queryByRole('searchbox')).not.toBeInTheDocument()
  expect(screen.getByRole('button',{name:'检索本页任务'})).toHaveFocus()
  expect(screen.getByText(/本页没有匹配的任务/)).toBeVisible()
  fireEvent.click(screen.getByRole('button',{name:'检索本页任务'}))
  fireEvent.click(screen.getByRole('button',{name:'清空检索'}))
  expect(container.querySelectorAll('article')).toHaveLength(2)
  fireEvent.click(screen.getByRole('button',{name:'卡片视图'}))
  expect(screen.getByRole('button',{name:'卡片视图'})).toHaveAttribute('aria-pressed','true')
  expect(container.querySelector('.hs-task-list--cards')).not.toBeNull()
 })
 it('passes an activity filter only through the existing campus task read',async()=>{
  const api=vi.fn(async(path:string)=>path==='/my/student-reference'?{reference:'test'}:page([first]))
  render(<SchoolStudentTasks api={api as SchoolApi} activityId={first.activityId}/>)
  await waitFor(()=>expect(api).toHaveBeenCalledWith('/my/activity-tasks?page=1&pageSize=25&activityId='+first.activityId))
  expect(screen.getByRole('link',{name:'查看全部任务'})).toHaveAttribute('href','/workspace/tasks')
 })
 it('moves authorized learner destinations into the banner while preserving page access boundaries',()=>{
  const navigate=vi.fn()
  render(<><SchoolLearnerMenu items={items} onNavigate={navigate}/><SchoolWorkspaceShell learner items={items} page="tasks" onNavigate={navigate}><p>授权任务</p></SchoolWorkspaceShell></>)
  expect(screen.queryByRole('navigation',{name:'工作台功能导航'})).not.toBeInTheDocument()
  const toggle=screen.getByText('',{selector:'summary[aria-label="校园功能"]'})
  fireEvent.click(toggle)
  expect(screen.getByRole('link',{name:'亲子关联'})).toBeVisible()
  fireEvent.click(screen.getByRole('link',{name:'亲子关联'}))
  expect(navigate).toHaveBeenCalledWith('family')
  expect(screen.queryByRole('link',{name:'个人信息编辑'})).not.toBeInTheDocument()
  expect(screen.queryByRole('link',{name:'群体报告'})).not.toBeInTheDocument()
 })
})

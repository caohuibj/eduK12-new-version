import {StrictMode} from 'react'
import {act,cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {afterEach,describe,expect,it,vi} from 'vitest'
import {ResearchCatalog,type CatalogApi,type CatalogGrant} from './ResearchCatalog'
const grant=(title:string):CatalogGrant=>({id:title,title,kind:'FORM',status:'ACTIVE',sourceRef:{kind:'FORM',sourceId:title,sourceVersion:1}})
function deferred(){let resolve!:(value:{list:CatalogGrant[]})=>void, reject!:(reason:Error)=>void;const promise=new Promise<{list:CatalogGrant[]}>((yes,no)=>{resolve=yes;reject=no});return {promise,resolve,reject}}
const onImport=vi.fn(async()=>{})
afterEach(()=>{cleanup();vi.restoreAllMocks()})
describe('researcher catalog request scope',()=>{
  it('joins StrictMode startup reads without caching a completed page',async()=>{
    const first=deferred()
    const api=vi.fn().mockReturnValueOnce(first.promise).mockResolvedValue({list:[grant('Fresh grant')]})
    const view=render(<StrictMode><ResearchCatalog projectId="p1" api={api as CatalogApi} busy={false} onImport={onImport}/></StrictMode>)
    expect(api).toHaveBeenCalledTimes(1)
    await act(async()=>first.resolve({list:Array.from({length:25},(_,i)=>grant('First '+i))}))
    await screen.findByRole('button',{name:'导入此版本：First 0'})
    fireEvent.click(screen.getByRole('button',{name:'目录下一页'}))
    await screen.findByRole('button',{name:'导入此版本：Fresh grant'})
    expect(api).toHaveBeenCalledTimes(2)
    fireEvent.click(screen.getByRole('button',{name:'目录上一页'}))
    await waitFor(()=>expect(api).toHaveBeenCalledTimes(3))
    expect(api).toHaveBeenLastCalledWith('/projects/p1/catalog?page=1')
    view.unmount()
  })
  it.each(['success','failure'] as const)('ignores late old-project %s after the new catalog is ready',async outcome=>{
    const old=deferred(),current=deferred()
    const api=vi.fn((path:string)=>path.includes('/p1/')?old.promise:current.promise)
    const view=render(<ResearchCatalog projectId="p1" api={api as CatalogApi} busy={false} onImport={onImport}/>)
    view.rerender(<ResearchCatalog projectId="p2" api={api as CatalogApi} busy={false} onImport={onImport}/>)
    await act(async()=>current.resolve({list:[grant('Current project')]}))
    await screen.findByRole('button',{name:'导入此版本：Current project'})
    await act(async()=>{if(outcome==='success')old.resolve({list:[grant('Old project')]});else old.reject(new Error('Old failure'))})
    expect(screen.getByRole('button',{name:'导入此版本：Current project'})).toBeEnabled()
    expect(screen.queryByText('Old failure')).not.toBeInTheDocument()
    expect(screen.queryByRole('button',{name:'导入此版本：Old project'})).not.toBeInTheDocument()
    expect(api).toHaveBeenCalledTimes(2)
  })
  it('does not allow a stale response to end the current project loading state',async()=>{
    const old=deferred(),current=deferred()
    const api=vi.fn().mockReturnValueOnce(old.promise).mockReturnValueOnce(current.promise)
    const view=render(<ResearchCatalog projectId="p1" api={api as CatalogApi} busy={false} onImport={onImport}/>)
    view.rerender(<ResearchCatalog projectId="p2" api={api as CatalogApi} busy={false} onImport={onImport}/>)
    await act(async()=>old.resolve({list:[grant('Old project')]}))
    expect(screen.getByText('正在加载授权目录…')).toBeInTheDocument()
    expect(screen.queryByRole('button',{name:'导入此版本：Old project'})).not.toBeInTheDocument()
    await act(async()=>current.resolve({list:[grant('Current project')]}))
    await screen.findByRole('button',{name:'导入此版本：Current project'})
  })
  it('retries a failed read and explicitly refreshes a settled result without reusing it',async()=>{
    const api=vi.fn().mockRejectedValueOnce(new Error('Retry needed')).mockResolvedValueOnce({list:[grant('First result')]}).mockResolvedValueOnce({list:[grant('Fresh result')]})
    render(<ResearchCatalog projectId="p1" api={api as CatalogApi} busy={false} onImport={onImport}/>)
    await screen.findByText('Retry needed')
    fireEvent.click(screen.getByRole('button',{name:'刷新授权目录'}))
    await screen.findByRole('button',{name:'导入此版本：First result'})
    fireEvent.click(screen.getByRole('button',{name:'刷新授权目录'}))
    await screen.findByRole('button',{name:'导入此版本：Fresh result'})
    expect(api).toHaveBeenCalledTimes(3)
    expect(screen.queryByText('Retry needed')).not.toBeInTheDocument()
  })
  it('clears already visible grants when the project changes',async()=>{
    const next=deferred()
    const api=vi.fn().mockResolvedValueOnce({list:[grant('Private old grant')]}).mockReturnValueOnce(next.promise)
    const view=render(<ResearchCatalog projectId="p1" api={api as CatalogApi} busy={false} onImport={onImport}/>)
    await screen.findByRole('button',{name:'导入此版本：Private old grant'})
    view.rerender(<ResearchCatalog projectId="p2" api={api as CatalogApi} busy={false} onImport={onImport}/>)
    expect(screen.queryByText('Private old grant')).not.toBeInTheDocument()
    expect(screen.queryByRole('button',{name:'导入此版本：Private old grant'})).not.toBeInTheDocument()
    await act(async()=>next.resolve({list:[]}))
  })

})

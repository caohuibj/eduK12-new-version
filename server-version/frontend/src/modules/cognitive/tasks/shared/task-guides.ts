export function resolveTaskGuide(testType?: string, engineVersion?: string): TaskGuide | undefined {
  if (!testType) return undefined
  // Historical engines for these identities used the analogy task.
  if ((testType === 'proofread' || testType === 'readingcomp') && engineVersion === '1.0.0') return cognitiveTaskGuides.wordanalogy
  return cognitiveTaskGuides[testType]
}

 it('jumps between mounted personal sections without losing an answer or filtering by school',async()=>{
  const fetch=session([organization('a'),organization('b')])
  vi.stubEnv('VITE_HUITEACHER_STUDENT_FEEDBACK_ENABLED','false')
  vi.stubEnv('VITE_HUITEACHER_IMPROVEMENT_ENABLED','false')
  render(<HuiteacherApp/>)
  const nav=await screen.findByRole('navigation',{name:'个人任务分区'})
  const primary=screen.getByRole('navigation',{name:'Teacher 工作台'})
  const banner=screen.getByRole('button',{name:'Teacher 首页'}).closest('header')!
  expect(within(banner).getByRole('navigation',{name:'Teacher 工作台'})).toBe(primary)
  expect(screen.getAllByRole('navigation',{name:'Teacher 工作台'})).toHaveLength(1)
  expect(within(banner).getByRole('navigation',{name:'产品导航'})).toBeInTheDocument()
  expect(within(nav).getAllByRole('link').map(link=>link.textContent)).toEqual(['参与测评','个人测评'])
  expect(within(nav).getByRole('link',{name:'参与测评'})).toHaveAttribute('aria-current','location')
  const info=screen.getByRole('button',{name:'个人空间说明'})
  const explanation=screen.getByText(/显示本人各学校的任务与个人测评，不随学校选择筛选/)
  expect(explanation).not.toBeVisible()
  fireEvent.mouseEnter(info)
  expect(explanation).toBeVisible()
  fireEvent.mouseLeave(info)
  expect(explanation).not.toBeVisible()
  fireEvent.click(info)
  expect(explanation).toBeVisible()
  fireEvent.pointerDown(document.body)
  expect(explanation).not.toBeVisible()
  fireEvent.click(info)
  fireEvent.keyDown(info,{key:'Escape'})
  expect(explanation).not.toBeVisible()
  fireEvent.click(within(nav).getByRole('link',{name:'参与测评'}))
  fireEvent.change(screen.getByLabelText('未提交答案'),{target:{value:'尚未提交的回答'}})
  fireEvent.click(within(nav).getByRole('link',{name:'个人测评'}))
  expect(screen.getByRole('region',{name:'个人测评'})).toHaveFocus()
  expect(screen.queryByRole('region',{name:'参与测评'})).not.toBeInTheDocument()
  expect(screen.getByLabelText('未提交答案')).not.toBeVisible()
  expect(within(nav).getByRole('link',{name:'个人测评'})).toHaveAttribute('aria-current','location')
  fireEvent.click(within(nav).getByRole('link',{name:'参与测评'}))
  expect(screen.getByRole('region',{name:'参与测评'})).toHaveFocus()
  fireEvent.change(screen.getByLabelText('当前学校管理范围'),{target:{value:'b'}})
  expect(screen.getByLabelText('未提交答案')).toHaveValue('尚未提交的回答')
  expect(within(nav).queryByRole('link',{name:'学生反馈'})).not.toBeInTheDocument()
  expect(within(nav).queryByRole('link',{name:'我的成长'})).not.toBeInTheDocument()
  expect(fetch.mock.calls.some(([,options])=>options?.method&&options.method!=='GET')).toBe(false)
 })

import {act,cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {afterEach,expect,it,vi} from 'vitest'
import HuiteacherApp from './HuiteacherApp'
import {emptyDefinition} from '../pages/scaleDefinitionEditorModel'
vi.mock('./HuiteacherPersonalSelf',()=>({HuiteacherPersonalSelf:()=> <p>本人个人测评</p>}))
vi.mock('./HuiteacherMyFormTasks',()=>({HuiteacherMyFormTasks:()=>null}))
vi.mock('./HuiteacherMyScaleTasks',()=>({HuiteacherMyScaleTasks:()=>null}))
vi.mock('./HuiteacherClassRelationships',()=>({HuiteacherClassRelationships:()=>null}))
const reply=(data:unknown)=>({ok:true,json:async()=>({code:0,message:'成功',data})})
afterEach(()=>{cleanup();vi.restoreAllMocks();vi.unstubAllGlobals()})
it('protects private drafts on Teacher tab and school changes, including pending writes',async()=>{
 const draft={id:'p1',kind:'SCALE',title:'私有量表',revision:1,contentHash:'hash',definition:emptyDefinition()}
 let resolveSave!:(value:unknown)=>void
 const confirm=vi.spyOn(window,'confirm').mockReturnValue(false)
 vi.stubGlobal('fetch',vi.fn(async(url:string,options?:RequestInit)=>{
  if(url.endsWith('/auth/me'))return reply({id:'psych',username:'Psych',role:'TEACHER',mustChangePassword:false,organizations:['a','b'].map(id=>({organizationId:id,organizationName:'学校 '+id,productAdmin:true}))})
  if(url.endsWith('/auth/csrf'))return reply({csrfToken:'test-csrf'})
  if(url.endsWith('/tool-authoring-capabilities'))return reply({canAuthor:true,authorableToolKinds:['SCALE','FORM']})
  if(url.endsWith('/private-tools/p1')&&options?.method==='PUT')return new Promise(resolve=>{resolveSave=resolve})
  if(url.endsWith('/private-tools/p1'))return reply(draft)
  if(url.endsWith('/private-tools'))return reply({list:[draft],nextCursor:null})
  return reply({list:[]})
 }))
 render(<HuiteacherApp/> )
 fireEvent.click(await screen.findByRole('button',{name:'我的工具'}))
 await screen.findByRole('button',{name:'编辑 私有量表'})
 fireEvent.change(screen.getByLabelText('工具名称'),{target:{value:'尚未创建的标题'}})
 fireEvent.click(screen.getByRole('button',{name:'教师成长'}))
 fireEvent.change(screen.getByLabelText('当前学校管理范围'),{target:{value:'b'}})
 expect(screen.getByLabelText('当前学校管理范围')).toHaveValue('a')
 expect(screen.getByLabelText('工具名称')).toHaveValue('尚未创建的标题')
 const unload=new Event('beforeunload',{cancelable:true});window.dispatchEvent(unload)
 expect(unload.defaultPrevented).toBe(true)
 confirm.mockClear()
 fireEvent.change(screen.getByLabelText('工具名称'),{target:{value:''}})
 fireEvent.click(screen.getByRole('button',{name:'编辑 私有量表'}))
 await waitFor(()=>expect(screen.getByRole('button',{name:'保存草稿'})).toBeEnabled())
 fireEvent.change(screen.getByLabelText('工具名称'),{target:{value:'保留私有草稿'}})
 fireEvent.click(screen.getByRole('button',{name:'教师成长'}))
 expect(screen.getByLabelText('工具名称')).toHaveValue('保留私有草稿')
 fireEvent.change(screen.getByLabelText('当前学校管理范围'),{target:{value:'b'}})
 expect(screen.getByLabelText('当前学校管理范围')).toHaveValue('a')
 expect(confirm).toHaveBeenCalledTimes(2)
 fireEvent.click(screen.getByRole('button',{name:'保存草稿'}))
 await waitFor(()=>expect(resolveSave).toBeTypeOf('function'))
 confirm.mockReturnValue(true)
 fireEvent.click(screen.getByRole('button',{name:'教师成长'}))
 expect(screen.getByLabelText('工具名称')).toHaveValue('保留私有草稿')
 await act(async()=>resolveSave(reply({revision:2,contentHash:'hash-2'})))
 await waitFor(()=>expect(screen.getByRole('button',{name:'保存草稿'})).toBeEnabled())
 fireEvent.click(screen.getByRole('button',{name:'教师成长'}))
 expect(await screen.findByText('本人个人测评')).toBeInTheDocument()
 expect(screen.queryByLabelText('工具名称')).not.toBeInTheDocument()
})
